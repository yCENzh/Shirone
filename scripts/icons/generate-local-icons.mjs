import {
	existsSync,
	mkdirSync,
	readdirSync,
	readFileSync,
	renameSync,
	writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { dirname, extname, join, relative } from "node:path";

const PACKAGE_NAME = "shirones";

const projectRoot = process.cwd();
const sourceRoot = join(projectRoot, "src");
const outputPath = join(sourceRoot, "generated", "local-icon-collections.ts");

/**
 * Extra roots to scan beyond `src/`.
 *
 * Two gaps make `src/` alone insufficient once the theme runs as a package:
 *
 * - The user's own content lives at `<contentRoot>/content`, outside `src/`. An
 *   icon referenced only from a post would otherwise be missing, so
 *   `Icon.svelte` could not render it.
 * - The theme's own components are not in the user's `src/` either — they live
 *   in the installed package. Without them the collection would contain the
 *   user's icons and none of the theme's, and every icon the theme itself uses
 *   would disappear.
 *
 * Roots that do not exist are skipped, so source mode — where the theme *is* the
 * project — resolves to exactly the pre-existing behaviour.
 */
function resolvePackageSrc() {
	try {
		const manifest = createRequire(join(projectRoot, "index.js")).resolve(
			`${PACKAGE_NAME}/package.json`,
		);
		const dir = dirname(manifest);
		// The published layout keeps sources under `src/`; a plain checkout has
		// them at the root next to package.json.
		for (const candidate of [join(dir, "src"), dir]) {
			if (existsSync(join(candidate, "components"))) return candidate;
		}
	} catch {
		// Not installed as a dependency: source mode, or a project that vendors
		// the theme another way. Nothing extra to scan.
	}
	return null;
}

const extraRoots = [];
{
	const configured = process.env.SHIRONES_CONTENT_ROOT?.trim() || PACKAGE_NAME;
	for (const root of configured
		.split(",")
		.map((r) => r.trim())
		.filter(Boolean)) {
		const absolute = join(projectRoot, root);
		// Skip a root that sits inside `src/`; the sweep below already covers it.
		if (!absolute.startsWith(`${sourceRoot}/`) && existsSync(absolute)) {
			extraRoots.push(absolute);
		}
	}
	const packageSrc = resolvePackageSrc();
	if (packageSrc) extraRoots.push(packageSrc);
}

const sourceExtensions = new Set([
	".astro",
	".md",
	".mdx",
	".svelte",
	".ts",
	".tsx",
]);
const iconPattern = /\b(?<prefix>[a-z][a-z0-9-]*):(?<name>[a-z0-9-]+)\b/g;
const iconPrefixes = new Set([
	"fa6-brands",
	"fa6-regular",
	"fa6-solid",
	"material-symbols",
	"simple-icons",
]);

function collectSourceFiles(directory) {
	const files = [];
	for (const entry of readdirSync(directory, { withFileTypes: true })) {
		const absolute = join(directory, entry.name);
		if (entry.isDirectory()) {
			if (entry.name !== "generated")
				files.push(...collectSourceFiles(absolute));
		} else if (sourceExtensions.has(extname(entry.name))) {
			files.push(absolute);
		}
	}
	return files;
}

const scannedFiles = [
	...collectSourceFiles(sourceRoot),
	// User content first: a post is the likeliest place for a new icon reference,
	// and ordering keeps the reported counts stable when both mention the same one.
	...extraRoots.flatMap(collectSourceFiles),
];

const requested = new Map();
for (const file of scannedFiles) {
	const source = readFileSync(file, "utf8");
	for (const match of source.matchAll(iconPattern)) {
		const { prefix, name } = match.groups;
		if (!iconPrefixes.has(prefix) || name === "xxx") continue;
		if (!requested.has(prefix)) requested.set(prefix, new Set());
		requested.get(prefix).add(name);
	}
}

const collections = [];
for (const [prefix, names] of [...requested].sort(([a], [b]) =>
	a.localeCompare(b),
)) {
	const iconSetPath = join(
		projectRoot,
		"node_modules",
		"@iconify-json",
		prefix,
		"icons.json",
	);
	if (!existsSync(iconSetPath)) {
		throw new Error(
			`[local-icons] Missing installed icon set @iconify-json/${prefix} for ${
				[...names][0]
			}`,
		);
	}
	const source = JSON.parse(readFileSync(iconSetPath, "utf8"));
	const icons = {};
	const aliases = {};

	function include(name, chain = []) {
		if (icons[name] || aliases[name]) return;
		if (source.icons?.[name]) {
			icons[name] = source.icons[name];
			return;
		}
		const alias = source.aliases?.[name];
		if (!alias) {
			throw new Error(
				`[local-icons] Unknown icon ${prefix}:${name} referenced from src`,
			);
		}
		if (chain.includes(name)) {
			throw new Error(
				`[local-icons] Circular alias ${prefix}:${[...chain, name].join(" -> ")}`,
			);
		}
		aliases[name] = alias;
		include(alias.parent, [...chain, name]);
	}

	for (const name of [...names].sort()) include(name);
	collections.push({
		prefix,
		...(source.width ? { width: source.width } : {}),
		...(source.height ? { height: source.height } : {}),
		icons,
		...(Object.keys(aliases).length ? { aliases } : {}),
	});
}

const output = `// Generated by scripts/icons/generate-local-icons.mjs. Do not edit.\nexport const localIconCollections = ${JSON.stringify(collections)} as const;\n`;
const temporaryPath = `${outputPath}.tmp`;
mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(temporaryPath, output, "utf8");
renameSync(temporaryPath, outputPath);

const count = collections.reduce(
	(total, collection) =>
		total +
		Object.keys(collection.icons).length +
		Object.keys(collection.aliases ?? {}).length,
	0,
);
console.log(
	`[local-icons] Wrote ${count} icons from ${collections.length} collections to ${relative(projectRoot, outputPath)}`,
);
